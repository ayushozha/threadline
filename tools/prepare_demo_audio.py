"""Align existing narration and create two quiet, original editorial sound cues."""
import argparse
import json
import math
import os
import re
import struct
import textwrap
import wave
from pathlib import Path

import httpx
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'assets/demo/narration'
load_dotenv(ROOT / '.env')


def timecode(seconds, separator=','):
    milliseconds = round(seconds * 1000)
    hours, remainder = divmod(milliseconds, 3600000)
    minutes, remainder = divmod(remainder, 60000)
    seconds, milliseconds = divmod(remainder, 1000)
    return f'{hours:02}:{minutes:02}:{seconds:02}{separator}{milliseconds:03}'


def align(audio, text_path):
    text = text_path.read_text(encoding='utf-8').strip()
    destination = audio.with_suffix('.alignment.json')
    if destination.exists():
        result = json.loads(destination.read_text(encoding='utf-8'))
    else:
        key = os.getenv('ELEVENLABS_API_KEY')
        if not key:
            raise SystemExit('Set ELEVENLABS_API_KEY in the local .env.')
        with audio.open('rb') as handle, httpx.Client(timeout=120) as client:
            response = client.post(
                'https://api.elevenlabs.io/v1/forced-alignment',
                headers={'xi-api-key': key},
                files={'file': (audio.name, handle, 'audio/mpeg')},
                data={'text': text},
            )
        if response.status_code != 200:
            raise SystemExit(f'Alignment HTTP {response.status_code}; existing narration preserved.')
        result = response.json()
        if not result.get('words'):
            raise SystemExit('No word timings returned; no captions generated.')
        destination.write_text(json.dumps(result, separators=(',', ':'), ensure_ascii=False), encoding='utf-8')
    words = [dict(word, text=word['text'].strip()) for word in result['words'] if word['text'].strip()]
    normalize = lambda value: re.sub(r'\W+', '', value.casefold())
    if normalize(' '.join(word['text'] for word in words)) != normalize(text):
        raise SystemExit('Aligned words differ from the source narration; inspect alignment before captioning.')
    cues, group = [], []
    for word in words:
        group.append(word)
        if re.search(r'[.!?][”"\']?$', word['text']):
            chunks = math.ceil(len(group) / 12)
            size = math.ceil(len(group) / chunks)
            cues.extend(group[start:start + size] for start in range(0, len(group), size))
            group = []
    if group:
        cues.append(group)
    srt, vtt = [], ['WEBVTT\n']
    for index, cue in enumerate(cues, 1):
        start, end = cue[0]['start'], max(cue[-1]['end'], cue[0]['start'] + .1)
        line = '\n'.join(textwrap.wrap(' '.join(word['text'] for word in cue), width=44))
        srt.append(f'{index}\n{timecode(start)} --> {timecode(end)}\n{line}\n')
        vtt.append(f'{timecode(start, ".")} --> {timecode(end, ".")}\n{line}\n')
    audio.with_suffix('.srt').write_text('\n'.join(srt), encoding='utf-8')
    audio.with_suffix('.vtt').write_text('\n'.join(vtt), encoding='utf-8')
    print(json.dumps({'aligned_words':len(words), 'cues':len(cues), 'last_word_seconds':words[-1]['end']}))


def effects():
    folder = ROOT / 'assets/demo/audio'
    folder.mkdir(exist_ok=True)
    rate = 48000
    for name, duration, frequencies in [('soft-transition', 1.1, (330, 495)), ('end-resolve', 1.8, (330, 440, 660))]:
        destination = folder / f'{name}.wav'
        if destination.exists():
            continue
        frames = bytearray()
        for index in range(round(duration * rate)):
            t = index / rate
            envelope = min(t / .1, 1) * math.exp(-3 * t / duration) * min((duration-t)/.15, 1)
            sample = sum(math.sin(2*math.pi*hz*t) for hz in frequencies) / len(frequencies)
            frames.extend(struct.pack('<h', round(sample * envelope * .1 * 32767)))
        with wave.open(str(destination), 'wb') as output:
            output.setparams((1, 2, rate, 0, 'NONE', 'not compressed'))
            output.writeframes(frames)
    (folder / 'README.md').write_text(
        '# Editorial sound cues\n\nOriginal synthesized tones, 48 kHz mono PCM. '
        'Soft transition: 1.1 seconds. End resolve: 1.8 seconds. '
        'Use quietly beneath the narration; these do not represent app feedback. '
        'Generated by `tools/prepare_demo_audio.py`; no music recording or external sample used.\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--audio', type=Path, default=FOLDER / 'narration-bella-v1.mp3')
    parser.add_argument('--text', type=Path, default=FOLDER / 'narration.txt')
    args = parser.parse_args()
    effects()
    align(args.audio.resolve(), args.text.resolve())
